// ==============================================================================
// notification_service.dart - Local Push Notification Service
// ==============================================================================
// This service manages local push notifications on the device.
// It sends alerts for:
// - Budget warnings (80%, 90%, 100% of budget used)
// - Category budget overruns
// - Achievement unlocks
// - Level ups
// - Streak milestones
// - Daily spending summaries
// - Tracking reminders
// - Recurring transaction (bill) reminders
//
// Key concepts:
// - "Local" notifications are generated by the app itself (not from a server)
// - Each notification has a unique ID so it can be updated/cancelled individually
// - Notifications are organized into "channels" (Android) for user control
// - Channels: budget_alerts, achievement_unlocked, level_up, streak_milestone,
//   recurring_reminders
//
// Uses the flutter_local_notifications package for cross-platform notifications.
// ==============================================================================

