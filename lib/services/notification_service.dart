  // ============================================================================
  // BILL REMINDERS & RECURRING TRANSACTION NOTIFICATIONS
  // ============================================================================

  // ==============================================================================
  // requestPermissions - Request Notification Permissions (Android 13+ and iOS)
  // ==============================================================================
  // Android 13+ (API 33+) requires the POST_NOTIFICATIONS runtime permission.
  // The user sees a system dialog: "Allow SmartFinance to send notifications?"
  // Without this, notifications are silently blocked on Android 13+ devices.
  //
  // iOS also requires explicit permission — same behavior as before.
  //
  // resolvePlatformSpecificImplementation<T>() returns the platform plugin
  // instance (Android or iOS) — returns null if on the other platform.
  // ?. is null-safe call — skips the call if the implementation doesn't exist.
  // ==============================================================================
  static Future<bool> requestPermissions() async {
    if (!_initialized) await initialize();

    // --- Android 13+ (API 33+): Request POST_NOTIFICATIONS runtime permission ---
    // On Android 12 and below this call is a no-op (permission auto-granted).
    // On Android 13+ it shows the system "Allow Notifications?" dialog once.
    final androidPlugin = _notifications
        .resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>();
    if (androidPlugin != null) {
      await androidPlugin.requestNotificationsPermission();
    }

    // --- iOS: Request permission to show alerts, badges, and play sounds ---
    final result = await _notifications
        .resolvePlatformSpecificImplementation<IOSFlutterLocalNotificationsPlugin>()
        ?.requestPermissions(alert: true, badge: true, sound: true);

    return result ?? true; // Default true — Android returns null here but is handled above
  }

  // ==============================================================================
  // scheduleRecurringReminder - Schedule a Bill Reminder Notification
  // ==============================================================================
  // Shows a notification reminding the user about an upcoming recurring transaction.
  //
  // Parameters:
  // - recurringId: ID of the recurring transaction (used to build notification ID)
  // - daysBeforeReminder: How many days before the due date to remind (default: 1)
  //
  // Notification ID formula: 10000 + recurringId
  // This avoids conflicts with other notification IDs (budget: 1000-2000,
  // gamification: 3000-5000, recurring: 10000+)
  //
  // Note: Currently shows immediate notifications for testing.
  // In production, you'd use zonedSchedule() for scheduled notifications.
  // ==============================================================================
  static Future<void> scheduleRecurringReminder({
    required int recurringId,
    required String name,
    required double amount,
    required String type,
    required DateTime nextExecution,
    int daysBeforeReminder = 1,
  }) async {
    await initialize();

    // Calculate when to show the reminder
    final reminderDate = nextExecution.subtract(Duration(days: daysBeforeReminder));

    // Don't schedule if the reminder date is already in the past
    if (reminderDate.isBefore(DateTime.now())) return;

    // Build unique notification ID: 10000 + recurringId
    final notificationId = 10000 + recurringId;

    const androidDetails = AndroidNotificationDetails(
      'recurring_reminders',             // Channel for bill reminders
      'Bill Reminders',
      channelDescription: 'Reminders for upcoming recurring transactions',
      importance: Importance.high,
      priority: Priority.high,
      ticker: 'Bill Reminder',
    );

    const iosDetails = DarwinNotificationDetails(
      presentAlert: true,
      presentBadge: true,
      presentSound: true,
    );

    const notificationDetails = NotificationDetails(
      android: androidDetails,
      iOS: iosDetails,
    );

    // Choose emoji based on transaction type
    final typeEmoji = type.toLowerCase() == 'income' ? '💰' : '💸';
    final title = 'Upcoming $type: $name';
    final body = '$typeEmoji RM ${amount.toStringAsFixed(2)} due on ${DateFormat('MMM dd, yyyy').format(nextExecution)}';

    try {
      // Show the reminder notification immediately
      await _notifications.show(
        notificationId,
        title,
        body,
        notificationDetails,
        payload: json.encode({                  // Attach data to the notification
          'type': 'recurring_reminder',         // So the app knows what to do when tapped
          'recurringId': recurringId,
          'name': name,
        }),
      );

      debugPrint('Scheduled reminder for $name (ID: $notificationId) on $reminderDate');
    } catch (e) {
      debugPrint('Error scheduling notification: $e');
    }
  }

  // Cancel a specific recurring reminder by its recurring transaction ID
  static Future<void> cancelRecurringReminder(int recurringId) async {
    await initialize();
    final notificationId = 10000 + recurringId;    // Reconstruct the notification ID
    await _notifications.cancel(notificationId);
    debugPrint('Cancelled reminder for recurring transaction $recurringId');
  }

  // ==============================================================================
  // Notification Settings (Persistent via SharedPreferences)
  // ==============================================================================

  // Get current notification settings from device storage
  static Future<Map<String, dynamic>> getNotificationSettings() async {
    final prefs = await SharedPreferences.getInstance();
    return {
      'enabled': prefs.getBool('notifications_enabled') ?? true,       // Default: enabled
      'daysBeforeReminder': prefs.getInt('days_before_reminder') ?? 1, // Default: 1 day before
      'soundEnabled': prefs.getBool('notification_sound') ?? true,     // Default: sound on
      'vibrationEnabled': prefs.getBool('notification_vibration') ?? true, // Default: vibration on
    };
  }

  // Save notification settings to device storage
  // Only saves fields that are provided (null fields are skipped)
  static Future<void> saveNotificationSettings({
    bool? enabled,
    int? daysBeforeReminder,
    bool? soundEnabled,
    bool? vibrationEnabled,
  }) async {
    final prefs = await SharedPreferences.getInstance();
    if (enabled != null) await prefs.setBool('notifications_enabled', enabled);
    if (daysBeforeReminder != null) await prefs.setInt('days_before_reminder', daysBeforeReminder);
    if (soundEnabled != null) await prefs.setBool('notification_sound', soundEnabled);
    if (vibrationEnabled != null) await prefs.setBool('notification_vibration', vibrationEnabled);
  }

  // ==============================================================================
  // scheduleAllRecurringReminders - Schedule Reminders for All Active Recurring Transactions
  // ==============================================================================
  // Called when the app starts or when recurring transactions are updated.
  // Goes through all recurring transactions and schedules reminders for active ones.
  //
  // Checks notification settings first - if notifications are disabled, does nothing.
  // ==============================================================================
  static Future<void> scheduleAllRecurringReminders(List<Map<String, dynamic>> recurringList) async {
    final settings = await getNotificationSettings();
    if (settings['enabled'] != true) return;      // Notifications disabled, skip

    final daysBeforeReminder = settings['daysBeforeReminder'] as int;

    for (var recurring in recurringList) {
      // The API model's to_dict() returns camelCase keys (isActive, nextExecution, etc.)
      // Handle both boolean true and integer 1 (database might return either)
      final isActive = recurring['isActive'] == true || recurring['isActive'] == 1;
      if (!isActive) continue;                    // Skip inactive ones

      try {
        final nextExecutionStr = recurring['nextExecution'];
        if (nextExecutionStr == null) continue;   // Skip if no next execution date

        final nextExecution = DateTime.parse(nextExecutionStr);

        // Schedule the reminder
        await scheduleRecurringReminder(
          recurringId: recurring['recurringId'],
          name: recurring['name'] ?? 'Unnamed',
          amount: (recurring['amount'] ?? 0.0).toDouble(),
          type: recurring['transactionType'] ?? 'expense',
          nextExecution: nextExecution,
          daysBeforeReminder: daysBeforeReminder,
        );
      } catch (e) {
        debugPrint('Error scheduling reminder for recurring ${recurring['RecurringId']}: $e');
      }
    }
  }

  // ==============================================================================
  // getUpcomingReminders - Get List of Upcoming Reminders for UI Display
  // ==============================================================================
  // Returns a list of upcoming recurring transactions within the next 30 days.
  // Used to display a "Upcoming Bills" section in the UI.
  //
  // Each item includes:
  // - recurringId, name, amount, type, category
  // - nextExecution: the due date
  // - daysUntil: how many days until the due date
  //
  // Results are sorted by date (soonest first).
  // ==============================================================================
  static Future<List<Map<String, dynamic>>> getUpcomingReminders(
    List<Map<String, dynamic>> recurringList,
  ) async {
    final List<Map<String, dynamic>> upcomingReminders = [];
    final now = DateTime.now();
    final thirtyDaysFromNow = now.add(const Duration(days: 30));

    for (var recurring in recurringList) {
      // Use camelCase keys — the API model's to_dict() returns camelCase
      final isActive = recurring['isActive'] == true || recurring['isActive'] == 1;
      if (!isActive) continue;

      try {
        final nextExecutionStr = recurring['nextExecution'];
        if (nextExecutionStr == null) continue;

        final nextExecution = DateTime.parse(nextExecutionStr);

        // Only include if within the next 30 days
        if (nextExecution.isAfter(now) && nextExecution.isBefore(thirtyDaysFromNow)) {
          upcomingReminders.add({
            'recurringId': recurring['recurringId'],
            'name': recurring['name'],
            'amount': recurring['amount'],
            'type': recurring['transactionType'],
            'category': recurring['category'],
            'nextExecution': nextExecution,
            'daysUntil': nextExecution.difference(now).inDays,   // Days until due
          });
        }
      } catch (e) {
        debugPrint('Error processing recurring ${recurring['RecurringId']}: $e');
      }
    }

    // Sort by date (soonest first)
    upcomingReminders.sort((a, b) =>
      (a['nextExecution'] as DateTime).compareTo(b['nextExecution'] as DateTime)
    );

    return upcomingReminders;
  }

