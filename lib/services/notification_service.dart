  // Plugin Instance and State
  // ==============================================================================
  // FlutterLocalNotificationsPlugin is the main entry point for all notification operations.
  // _initialized flag prevents initializing the plugin multiple times.
  // ==============================================================================
  static final FlutterLocalNotificationsPlugin _notifications =
      FlutterLocalNotificationsPlugin();

  static bool _initialized = false;    // Track if plugin has been initialized

  // ==============================================================================
  // initialize - Set Up the Notification Plugin
  // ==============================================================================
  // Must be called before showing any notifications.
  // Configures platform-specific settings for Android and iOS.
  //
  // AndroidInitializationSettings: Specifies the notification icon
  //   '@mipmap/ic_launcher' = the app's launcher icon
  //
  // DarwinInitializationSettings (iOS):
  //   Requests permission to show alerts, badges, and play sounds
  //
  // The _initialized flag ensures this only runs once even if called multiple times.
  // ==============================================================================
  static Future<void> initialize() async {
    if (_initialized) return;          // Already initialized, skip

    // Android notification settings
    const androidSettings = AndroidInitializationSettings('@mipmap/ic_launcher');

    // iOS notification settings (Darwin = Apple's OS kernel name)
    const iosSettings = DarwinInitializationSettings(
      requestAlertPermission: true,    // Ask to show alert popups
      requestBadgePermission: true,    // Ask to show badge numbers on app icon
      requestSoundPermission: true,    // Ask to play notification sounds
    );

    // Combine platform settings
    const initializationSettings = InitializationSettings(
      android: androidSettings,
      iOS: iosSettings,
    );

    // Initialize the plugin with the settings
    await _notifications.initialize(initializationSettings);
    _initialized = true;
  }

  // ==============================================================================
  // BUDGET NOTIFICATIONS
  // ==============================================================================

  // ==============================================================================
  // showBudgetAlert - Show a Budget-Related Notification
  // ==============================================================================
  // Creates and displays a notification in the "budget_alerts" channel.
  //
  // NotificationDetails configures how the notification looks and behaves:
  // - channelId: Groups notifications for user control (Android Settings)
  // - importance/priority: HIGH makes the notification pop up on screen
  // - ticker: Text shown in the status bar briefly
  //
  // notificationId: Each notification needs a unique int ID.
  // Using the same ID updates the existing notification instead of creating a new one.
  // ==============================================================================
  static Future<void> showBudgetAlert({
    required String title,
    required String body,
    required int notificationId,
  }) async {
    await initialize();                 // Ensure plugin is initialized

    // Android-specific notification appearance
    const androidDetails = AndroidNotificationDetails(
      'budget_alerts',                  // Channel ID (unique identifier)
      'Budget Alerts',                  // Channel name (shown in Android Settings)
      channelDescription: 'Alerts for budget spending and limits',
      importance: Importance.high,      // HIGH = shows as popup
      priority: Priority.high,          // HIGH = treated as urgent
      ticker: 'Budget Alert',          // Brief text in status bar
    );

    // iOS-specific notification appearance
    const iosDetails = DarwinNotificationDetails(
      presentAlert: true,               // Show the notification alert
      presentBadge: true,               // Update the app badge count
      presentSound: true,               // Play a sound
    );

    // Combine both platform details
    const notificationDetails = NotificationDetails(
      android: androidDetails,
      iOS: iosDetails,
    );

    // Show the notification
    await _notifications.show(
      notificationId,                   // Unique ID for this notification
      title,                            // Notification title
      body,                             // Notification body text
      notificationDetails,              // Platform-specific appearance
    );
  }

  // ==============================================================================
  // checkBudgetAndAlert - Analyze Budget and Send Appropriate Alerts
  // ==============================================================================
  // Checks the budget usage percentage and sends different alerts:
  // - 100%+ (exceeded): Red alert notification
  // - 90-99% (warning): Yellow warning notification
  // - 80-89% (caution): Blue caution notification
  //
  // Also checks each individual category for overruns.
  //
  // Notification IDs:
  // - 1000-1002: Overall budget alerts
  // - 2000+: Individual category alerts (incremented per category)
  // ==============================================================================
  static Future<void> checkBudgetAndAlert(BudgetModel budget) async {
    final percentage = budget.percentageUsed;     // Get the overall usage percentage

    // Alert for overall budget status
    // isOverBudget is derived from percentageUsed >= 100, so we check it directly
    // (the old condition `percentage >= 100 && !budget.isOverBudget` was always false)
    if (budget.isOverBudget) {
      // Budget has been exceeded
      await showBudgetAlert(
        title: '🚨 Budget Exceeded!',
        body: 'You\'ve spent RM ${budget.totalSpent.toStringAsFixed(2)} of your RM ${budget.totalBudget.toStringAsFixed(2)} budget.',
        notificationId: 1000,
      );
    } else if (percentage >= 90 && percentage < 100) {
      // Approaching limit (90-99%)
      await showBudgetAlert(
        title: '⚠️ Budget Warning',
        body: 'You\'ve used ${percentage.toStringAsFixed(0)}% of your monthly budget. RM ${budget.totalRemaining.toStringAsFixed(2)} remaining.',
        notificationId: 1001,
      );
    } else if (percentage >= 80 && percentage < 90) {
      // Caution (80-89%)
      await showBudgetAlert(
        title: '📊 Budget Alert',
        body: 'You\'ve spent ${percentage.toStringAsFixed(0)}% of your budget. Watch your spending!',
        notificationId: 1002,
      );
    }

    // Check each individual category budget
    int categoryAlertId = 2000;        // Starting ID for category alerts
    for (var category in budget.categories) {
      if (category.isOverBudget) {
        // Category exceeded its allocated budget
        await showBudgetAlert(
          title: '🚨 ${category.categoryName} Over Budget',
          body: 'You\'ve exceeded your ${category.categoryName} budget by RM ${(-category.remaining).toStringAsFixed(2)}.',
          // -category.remaining gives the amount over budget (remaining is negative when over)
          notificationId: categoryAlertId++,    // Post-increment: use value, then add 1
        );
      } else if (category.percentageUsed >= 90) {
        // Category approaching its limit (90%+)
        await showBudgetAlert(
          title: '⚠️ ${category.categoryName} Warning',
          body: '${category.percentageUsed.toStringAsFixed(0)}% of ${category.categoryName} budget used. RM ${category.remaining.toStringAsFixed(2)} remaining.',
          notificationId: categoryAlertId++,
        );
      }
    }
  }

